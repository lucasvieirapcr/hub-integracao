-- Rotinas usadas apenas pelo simulador na recarga do ERP.

create or replace package pkg_admin authid definer as
    procedure reset_data;

    -- Ajusta IDENTITY e invoice_number_seq após carga com IDs explícitos.
    procedure sync_identities;
end pkg_admin;
/

create or replace package body pkg_admin as

    c_package constant varchar2(30) := 'PKG_ADMIN';

    type t_names is table of varchar2(128);
    -- filhas antes das pais
    c_tables constant t_names := t_names(
        'INVOICE_ITEMS', 'INVOICES', 'ORDER_ITEM_ALLOCATIONS', 'ORDER_ITEMS', 'ORDERS',
        'STOCK_MOVEMENTS', 'STOCK', 'LOTS', 'PRICE_TABLE_ITEMS', 'CUSTOMERS', 'PRODUCTS',
        'WAREHOUSES', 'PRICE_TABLES', 'SIM_RUNS'
    );

    procedure set_foreign_keys(p_enabled in boolean) is
    begin
        for r in (select table_name, constraint_name from user_constraints where constraint_type = 'R') loop
            execute immediate 'alter table ' || dbms_assert.simple_sql_name(r.table_name)
                || case when p_enabled then ' enable' else ' disable' end
                || ' constraint ' || dbms_assert.simple_sql_name(r.constraint_name);
        end loop;
    end set_foreign_keys;

    procedure reset_data is
    begin
        -- TRUNCATE exige FKs desabilitadas
        set_foreign_keys(false);
        for i in 1 .. c_tables.count loop
            execute immediate 'truncate table ' || dbms_assert.simple_sql_name(c_tables(i));
        end loop;
        set_foreign_keys(true);
    exception
        when others then
            hub_audit.pkg_error_log.log_error(c_package, 'RESET_DATA', null, sqlcode, sqlerrm);
            begin
                set_foreign_keys(true);
            exception
                when others then
                    null; -- o erro que importa é o original, relançado abaixo
            end;
            raise;
    end reset_data;

    procedure sync_identities is
        l_next_invoice number;
    begin
        for r in (select table_name, column_name from user_tab_identity_cols) loop
            execute immediate 'alter table ' || dbms_assert.simple_sql_name(r.table_name)
                || ' modify ' || dbms_assert.simple_sql_name(r.column_name)
                || ' generated by default on null as identity (start with limit value)';
        end loop;

        select nvl(max(invoice_number), 0) + 1 into l_next_invoice from invoices;
        execute immediate 'alter sequence invoice_number_seq restart start with ' || l_next_invoice;
    exception
        when others then
            hub_audit.pkg_error_log.log_error(c_package, 'SYNC_IDENTITIES', null, sqlcode, sqlerrm);
            raise;
    end sync_identities;

end pkg_admin;
/
