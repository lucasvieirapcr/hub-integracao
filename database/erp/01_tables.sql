-- Tabelas do ERP. Colunas *_at em UTC.
-- IDENTITY "by default on null" aceita IDs explícitos (carga histórica).
-- IF NOT EXISTS não altera tabelas existentes: mudanças de estrutura via ALTER TABLE.

create table if not exists price_tables (
    price_table_id  number(10)     generated by default on null as identity,
    name            varchar2(100)  not null,
    discount_pct    number(5, 2)   default 0 not null,
    created_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    updated_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    constraint pk_price_tables primary key (price_table_id),
    constraint ck_price_tables_discount check (discount_pct between 0 and 100)
);

create table if not exists warehouses (
    warehouse_id    number(10)     generated by default on null as identity,
    warehouse_code  varchar2(10)   not null,
    name            varchar2(100)  not null,
    city_ibge_code  number(7)      not null,
    state           char(2)        not null,
    created_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    updated_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    constraint pk_warehouses primary key (warehouse_id),
    constraint uq_warehouses_code unique (warehouse_code)
);

create table if not exists customers (
    customer_id     number(10)     generated by default on null as identity,
    customer_code   varchar2(20)   not null,
    legal_name      varchar2(200)  not null,
    trade_name      varchar2(120)  not null,
    cnpj            char(14)       not null,
    customer_type   varchar2(10)   not null,
    city_ibge_code  number(7)      not null,
    state           char(2)        not null,
    price_table_id  number(10)     not null,
    warehouse_id    number(10)     not null,
    credit_limit    number(14, 2)  default 0 not null,
    is_active       char(1)        default 'Y' not null,
    created_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    updated_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    constraint pk_customers primary key (customer_id),
    constraint uq_customers_code unique (customer_code),
    constraint ck_customers_type check (customer_type in ('PHARMACY', 'CLINIC', 'HOSPITAL')),
    constraint ck_customers_active check (is_active in ('Y', 'N')),
    constraint fk_customers_price_table foreign key (price_table_id) references price_tables (price_table_id),
    constraint fk_customers_warehouse foreign key (warehouse_id) references warehouses (warehouse_id)
);

create table if not exists products (
    product_id             number(10)     generated by default on null as identity,
    product_code           varchar2(20)   not null,
    description            varchar2(300)  not null,
    category               varchar2(40)   not null,
    active_ingredient      varchar2(100)  not null,
    manufacturer           varchar2(100)  not null,
    pack_size              number(6)      not null,
    requires_prescription  char(1)        default 'N' not null,
    list_price             number(12, 2)  not null,
    is_active              char(1)        default 'Y' not null,
    created_at             timestamp(6)   default sys_extract_utc(systimestamp) not null,
    updated_at             timestamp(6)   default sys_extract_utc(systimestamp) not null,
    constraint pk_products primary key (product_id),
    constraint uq_products_code unique (product_code),
    constraint ck_products_rx check (requires_prescription in ('Y', 'N')),
    constraint ck_products_active check (is_active in ('Y', 'N')),
    constraint ck_products_price check (list_price >= 0)
);

create table if not exists price_table_items (
    price_table_id  number(10)     not null,
    product_id      number(10)     not null,
    valid_from      date           not null,
    valid_to        date,
    unit_price      number(12, 2)  not null,
    created_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    constraint pk_price_table_items primary key (price_table_id, product_id, valid_from),
    constraint ck_price_table_items_period check (valid_to is null or valid_to >= valid_from),
    constraint fk_price_table_items_table foreign key (price_table_id) references price_tables (price_table_id),
    constraint fk_price_table_items_product foreign key (product_id) references products (product_id)
);

create table if not exists lots (
    lot_id           number(10)    generated by default on null as identity,
    product_id       number(10)    not null,
    lot_number       varchar2(30)  not null,
    manufactured_on  date          not null,
    expires_on       date          not null,
    created_at       timestamp(6)  default sys_extract_utc(systimestamp) not null,
    constraint pk_lots primary key (lot_id),
    constraint uq_lots_product_number unique (product_id, lot_number),
    constraint ck_lots_dates check (expires_on > manufactured_on),
    constraint fk_lots_product foreign key (product_id) references products (product_id)
);

-- busca FEFO
create index if not exists ix_lots_product_expiry on lots (product_id, expires_on);

create table if not exists stock (
    warehouse_id  number(10)    not null,
    lot_id        number(10)    not null,
    qty_on_hand   number(12)    default 0 not null,
    qty_reserved  number(12)    default 0 not null,
    updated_at    timestamp(6)  default sys_extract_utc(systimestamp) not null,
    constraint pk_stock primary key (warehouse_id, lot_id),
    constraint ck_stock_reserved check (qty_reserved >= 0 and qty_reserved <= qty_on_hand),
    constraint fk_stock_warehouse foreign key (warehouse_id) references warehouses (warehouse_id),
    constraint fk_stock_lot foreign key (lot_id) references lots (lot_id)
);

create index if not exists ix_stock_lot on stock (lot_id);

create table if not exists stock_movements (
    movement_id    number(12)    generated by default on null as identity,
    warehouse_id   number(10)    not null,
    lot_id         number(10)    not null,
    movement_type  varchar2(10)  not null,
    quantity       number(12)    not null,
    order_id       number(12),
    created_at     timestamp(6)  default sys_extract_utc(systimestamp) not null,
    constraint pk_stock_movements primary key (movement_id),
    constraint ck_stock_movements_type check (movement_type in ('IN', 'RESERVE', 'RELEASE', 'OUT')),
    constraint ck_stock_movements_qty check (quantity > 0)
);

create index if not exists ix_stock_movements_lot on stock_movements (lot_id);
create index if not exists ix_stock_movements_order on stock_movements (order_id);

create table if not exists orders (
    order_id            number(12)     generated by default on null as identity,
    customer_id         number(10)     not null,
    warehouse_id        number(10)     not null,
    channel             varchar2(10)   not null,
    external_order_ref  varchar2(40),
    order_date          date           not null,
    status              varchar2(10)   not null,
    total_amount        number(14, 2)  default 0 not null,
    created_at          timestamp(6)   default sys_extract_utc(systimestamp) not null,
    updated_at          timestamp(6)   default sys_extract_utc(systimestamp) not null,
    constraint pk_orders primary key (order_id),
    constraint uq_orders_external_ref unique (external_order_ref),
    constraint ck_orders_channel check (channel in ('PHONE', 'SALES_REP', 'B2B')),
    constraint ck_orders_status check (status in ('OPEN', 'CONFIRMED', 'INVOICED', 'CANCELLED')),
    constraint fk_orders_customer foreign key (customer_id) references customers (customer_id),
    constraint fk_orders_warehouse foreign key (warehouse_id) references warehouses (warehouse_id)
);

create index if not exists ix_orders_customer on orders (customer_id);
create index if not exists ix_orders_updated_at on orders (updated_at);
create index if not exists ix_orders_order_date on orders (order_date);

create table if not exists order_items (
    order_id     number(12)     not null,
    line_number  number(4)      not null,
    product_id   number(10)     not null,
    quantity     number(10)     not null,
    unit_price   number(12, 2)  not null,
    line_amount  number(14, 2)  generated always as (round(quantity * unit_price, 2)) virtual,
    constraint pk_order_items primary key (order_id, line_number),
    constraint ck_order_items_qty check (quantity > 0),
    constraint ck_order_items_price check (unit_price >= 0),
    constraint fk_order_items_order foreign key (order_id) references orders (order_id),
    constraint fk_order_items_product foreign key (product_id) references products (product_id)
);

create index if not exists ix_order_items_product on order_items (product_id);

create table if not exists order_item_allocations (
    order_id      number(12)  not null,
    line_number   number(4)   not null,
    lot_id        number(10)  not null,
    warehouse_id  number(10)  not null,
    quantity      number(10)  not null,
    constraint pk_order_item_allocations primary key (order_id, line_number, lot_id),
    constraint ck_order_item_allocations_qty check (quantity > 0),
    constraint fk_allocations_item foreign key (order_id, line_number) references order_items (order_id, line_number),
    constraint fk_allocations_lot foreign key (lot_id) references lots (lot_id),
    constraint fk_allocations_warehouse foreign key (warehouse_id) references warehouses (warehouse_id)
);

create index if not exists ix_allocations_lot on order_item_allocations (lot_id);

create sequence if not exists invoice_number_seq start with 1 cache 100;

create table if not exists invoices (
    invoice_id      number(12)     generated by default on null as identity,
    invoice_number  number(10)     not null,
    order_id        number(12)     not null,
    issued_at       timestamp(6)   not null,
    total_amount    number(14, 2)  default 0 not null,
    status          varchar2(10)   not null,
    created_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    updated_at      timestamp(6)   default sys_extract_utc(systimestamp) not null,
    constraint pk_invoices primary key (invoice_id),
    constraint uq_invoices_number unique (invoice_number),
    constraint uq_invoices_order unique (order_id),
    constraint ck_invoices_status check (status in ('ISSUED', 'CANCELLED')),
    constraint fk_invoices_order foreign key (order_id) references orders (order_id)
);

create index if not exists ix_invoices_updated_at on invoices (updated_at);

create table if not exists invoice_items (
    invoice_id   number(12)     not null,
    line_number  number(4)      not null,
    product_id   number(10)     not null,
    lot_id       number(10)     not null,
    quantity     number(10)     not null,
    unit_price   number(12, 2)  not null,
    line_amount  number(14, 2)  generated always as (round(quantity * unit_price, 2)) virtual,
    constraint pk_invoice_items primary key (invoice_id, line_number),
    constraint ck_invoice_items_qty check (quantity > 0),
    constraint fk_invoice_items_invoice foreign key (invoice_id) references invoices (invoice_id),
    constraint fk_invoice_items_product foreign key (product_id) references products (product_id),
    constraint fk_invoice_items_lot foreign key (lot_id) references lots (lot_id)
);

-- rastreabilidade lote -> nota
create index if not exists ix_invoice_items_lot on invoice_items (lot_id);
create index if not exists ix_invoice_items_product on invoice_items (product_id);

-- Dias já simulados.
create table if not exists sim_runs (
    sim_date          date          not null,
    orders_created    number(10)    not null,
    orders_cancelled  number(10)    not null,
    ran_at            timestamp(6)  default sys_extract_utc(systimestamp) not null,
    constraint pk_sim_runs primary key (sim_date)
);

